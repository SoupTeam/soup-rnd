"""Tests for the F3 laptop setup helpers (benchmarks/harness/f3_setup.py, F3 ticket 07).

Pure logic only: no network, no GPU, no installs.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

HARNESS = Path(__file__).resolve().parents[1] / "benchmarks" / "harness"
REPO = Path(__file__).resolve().parents[1]


@pytest.fixture(scope="module")
def setup_mod():
    path = HARNESS / "f3_setup.py"
    assert path.exists(), "benchmarks/harness/f3_setup.py is missing"
    name = "_f3_setup_test_module"
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(name, None)
    return module


LOCK = """\
# This file was autogenerated by uv
accelerate==1.12.0
    # via
    #   trl
    #   unsloth
cut-cross-entropy==25.1.1
    # via unsloth-zoo
torch==2.9.1
    # via
    #   accelerate
xformers==0.0.33.post2
    # via unsloth
yarl==1.22.0
    # via aiohttp
"""


def test_filter_lock_drops_banned_packages_and_their_comments(setup_mod):
    result = setup_mod.filter_lock(LOCK, ("cut-cross-entropy", "xformers"))
    assert "cut-cross-entropy" not in result
    assert "xformers" not in result
    assert "via unsloth-zoo" not in result
    assert "torch==2.9.1\n    # via\n    #   accelerate\n" in result
    assert "accelerate==1.12.0\n    # via\n    #   trl\n    #   unsloth\n" in result
    assert result.startswith("# This file was autogenerated")


def test_filter_lock_drops_banned_names_from_other_packages_via_lists(setup_mod):
    text = "numpy==2.0\n    # via\n    #   cut-cross-entropy\n    #   torch\n"
    assert setup_mod.filter_lock(text, ("cut-cross-entropy",)) == (
        "numpy==2.0\n    # via\n    #   torch\n"
    )


def test_filter_lock_matches_names_case_and_underscore_insensitive(setup_mod):
    text = "Cut_Cross_Entropy==1.0\n    # via x\nnumpy==2.0\n"
    assert setup_mod.filter_lock(text, ("cut-cross-entropy",)) == "numpy==2.0\n"


def test_banned_installed_reports_names(setup_mod):
    installed = ["torch", "xFormers", "cut_cross_entropy", "numpy"]
    found = setup_mod.banned_installed(installed, ("cut-cross-entropy", "xformers"))
    assert found == ["cut-cross-entropy", "xformers"]


def test_banned_installed_empty_when_clean(setup_mod):
    assert setup_mod.banned_installed(["torch"], ("xformers",)) == []


def test_power_cap_problem_flags_ten_watts(setup_mod):
    text = "        Current Power Limit                            : 10.00 W\n"
    assert "10" in setup_mod.power_cap_problem(text)


def test_power_cap_problem_none_at_default(setup_mod):
    text = (
        "    GPU Power Readings\n"
        "        Current Power Limit                            : 80.00 W\n"
        "        Default Power Limit                            : 80.00 W\n"
    )
    assert setup_mod.power_cap_problem(text) is None


def test_power_cap_problem_reports_unreadable_output(setup_mod):
    assert "could not read" in setup_mod.power_cap_problem("no gpu here")


def test_dataset_sha256_is_stable_and_order_sensitive(setup_mod):
    rows = [[1, 2, 3], [4, 5]]
    assert setup_mod.dataset_sha256(rows) == setup_mod.dataset_sha256([[1, 2, 3], [4, 5]])
    assert setup_mod.dataset_sha256(rows) != setup_mod.dataset_sha256([[4, 5], [1, 2, 3]])


def test_dataset_sha256_separates_row_boundaries(setup_mod):
    assert setup_mod.dataset_sha256([[1, 2], [3]]) != setup_mod.dataset_sha256([[1], [2, 3]])


def test_dataset_sha256_known_value(setup_mod):
    # sha256 of the JSON text '[[1,2],[3]]' computed independently with sha256sum.
    assert (
        setup_mod.dataset_sha256([[1, 2], [3]])
        == "2ce1506f23766b649ef41e6bdfe0fdbe4f0511b691fae88138226d089ed82a4b"
    )


def test_fetch_commands_pin_the_commit(setup_mod, tmp_path):
    commands = setup_mod.fetch_commands("https://example.org/r.git", "abc123", tmp_path / "r")
    flat = [" ".join(command) for command in commands]
    assert any("clone" in line for line in flat)
    assert any("checkout" in line and "abc123" in line for line in flat)


def test_fetch_commands_refuse_a_destination_inside_the_repo(setup_mod):
    with pytest.raises(ValueError, match="inside the repository"):
        setup_mod.fetch_commands("https://example.org/r.git", "abc", REPO / "foreign")
